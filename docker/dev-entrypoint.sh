#!/bin/sh
# Точка входа дев-контейнера. Снимает две проблемы, которые выглядят одинаково —
# «после git pull сайт стал другим» — и ищутся часами.
set -e

# 1. Зависимости. node_modules лежит в томе, который переживает и
#    `docker compose up`, и `--build`: Compose переносит тома в новый контейнер,
#    а не создаёт заново. После смены package-lock.json в контейнере остаются
#    старые пакеты. Сверяем контрольную сумму и доустанавливаем сами.
LOCK=/app/package-lock.json
STAMP=/app/node_modules/.lock-checksum

want=$(md5sum "$LOCK" | cut -d' ' -f1)
have=$(cat "$STAMP" 2>/dev/null || echo '')

if [ "$want" != "$have" ]; then
  echo "› зависимости разошлись с package-lock.json — ставлю заново"
  npm ci
  echo "$want" > "$STAMP"
fi

# 2. Кэш сборки. Turbopack не замечает правок, сделанных пока контейнер стоял:
#    после git pull он отдаёт CSS, собранный до правок, — новые секции приезжают
#    без стилей, и это ловится только глазами. Проверено на globals.css: правила
#    появились в чанке лишь после удаления каталога сборки.
#    Стоит одну пересборку при старте, экономит часы поисков.
rm -rf /app/.next/*  2>/dev/null || true
rm -rf /app/.next/.* 2>/dev/null || true

exec "$@"
