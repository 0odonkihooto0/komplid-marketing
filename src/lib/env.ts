/**
 * Чтение переменных окружения со значением по умолчанию.
 *
 * `process.env.X ?? fallback` здесь не годится: `??` отсекает только undefined,
 * а незаполненная строка в .env-файле приезжает пустой строкой и побеждает
 * значение по умолчанию. Файл .env.local создаётся копированием .env.example,
 * где половина ключей объявлена пустыми, — то есть это состояние по умолчанию,
 * а не редкий случай.
 *
 * Чем это оборачивалось: LEADS_DATA_DIR= превращал каталог хранения лидов
 * в пустую строку, mkdir('') падал, и /api/lead отдавал 500 на каждую заявку.
 * На пре-лонче сбор базы — главная задача сайта.
 */
export function envOr(value: string | undefined, fallback: string): string {
  const trimmed = value?.trim();
  return trimmed ? trimmed : fallback;
}
