/**
 * Реестр форм исполнительной документации.
 *
 * Данные перенесены из прототипа «Реестр форм ИД» (архив komplidLanding).
 * Правило §21 действует и здесь: заявляем только то, что работает.
 *
 * Ссылки на несуществующие разделы (/otkazy, /kurs) вычищены, а короткие
 * обозначения СП развёрнуты в реальные слаги корпуса — иначе перелинковка
 * вела бы в 404.
 */


export interface FormSigner {
  role: string;
  /** Что именно подтверждает подпись этой стороны */
  confirms: string;
  /** Обязательно, при авторском надзоре, если привлечён — и так далее */
  required: string;
}

export interface FormAppendix {
  title: string;
  note: string;
}

export interface FormStep {
  when: string;
  title: string;
  note: string;
}

export interface FormReturn {
  /** Доля возвратов по этой причине — оценка автора прототипа, не наша статистика */
  share: string;
  /** Из-за чего форму возвращают */
  text: string;
}

export interface FormFaq {
  q: string;
  a: string;
}

export interface DocForm {
  code: string;
  slug: string;
  name: string;
  section: string;
  /** Виды работ, на которых форма применяется */
  works: readonly string[];
  format: string;
  fileType: string;
  /** Сколько и до какого момента хранится */
  storage: string;
  /** Одна строка для карточки в каталоге */
  summary: string;
  /** Прямой ответ «когда оформляется» — первым абзацем страницы, для AEO */
  answer: string;
  /** Нормативное основание */
  basis: string;
  basisNote: string;
  signers: readonly FormSigner[];
  appendices: readonly FormAppendix[];
  timeline: readonly FormStep[];
  returns: readonly FormReturn[];
  faq: readonly FormFaq[];
  /** Слаги связанных форм */
  related: readonly string[];
  /**
   * Слаг бланка в /shablony, если он у нас есть.
   *
   * Реестр форм отвечает на вопрос «как это оформляется», каталог шаблонов
   * отдаёт готовый файл. Раньше эти два раздела не были связаны вовсе:
   * человек читал про АОСР и уходил искать бланк поиском.
   */
  templateSlug?: string;
}

