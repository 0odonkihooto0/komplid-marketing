/** Пункт по слагу документа и слагу пункта из адреса страницы. */
export function getClauseByPath(docSlug: string, clausePath: string): SpClause | undefined {
  return SP_CLAUSES.find(
    (c) => clauseDocSlug(c) === docSlug && clauseUrlPart(c) === clausePath,
  );
}

/** Пункт по внутреннему идентификатору — для перелинковки между пунктами. */
export function getClause(id: string): SpClause | undefined {
  return SP_CLAUSES.find((c) => c.id === id);
}

/** Слаг документа в адресе пункта. Для документов вне корпуса — синтетический. */
export function clauseDocSlug(clause: SpClause): string {
  return CLAUSE_DOCS[clause.docKey]?.slug ?? FALLBACK_DOC_SLUGS[clause.docKey] ?? clause.docKey;
}

/** Часть адреса с номером пункта: 6.13 → p-6-13. */
export function clauseUrlPart(clause: SpClause): string {
  return `p-${clause.clause.replace(/\./g, '-')}`;
}

/** Полный адрес страницы пункта. */
export function clauseUrl(clause: SpClause): string {
  return `/normativ/${clauseDocSlug(clause)}/${clauseUrlPart(clause)}`;
}

