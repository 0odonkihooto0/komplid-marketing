import { describe, it, expect } from 'vitest';
import { slug as githubSlug } from 'github-slugger';
import { slugify, extractHeadings } from './toc';

describe('slugify', () => {
  it('сохраняет кириллицу — русские заголовки не схлопываются в «-»', () => {
    expect(slugify('Что такое АОСР и для чего он нужен?')).toBe(
      'что-такое-аоср-и-для-чего-он-нужен',
    );
  });

  it('сохраняет цифры и дефисы внутри слов (КС-2)', () => {
    expect(slugify('Как заполнить КС-2: пошагово')).toBe('как-заполнить-кс-2-пошагово');
  });

  it('удаляет пунктуацию и кавычки', () => {
    expect(slugify('«Цитата» и (скобки)')).toBe('цитата-и-скобки');
  });

  // Якоря оглавления обязаны совпадать с id, которые rehype-slug
  // (github-slugger) проставляет заголовкам при рендере статьи —
  // иначе ссылки бьют мимо. Проверяем паритет на типовых заголовках.
  it('даёт те же id, что github-slugger (rehype-slug)', () => {
    const headings = [
      'Что такое АОСР и для чего он нужен?',
      'Как заполнить КС-2: пошагово',
      'Частые вопросы',
      'Сравнение Komplid vs Excel',
      'Шаблон 2026 года — образец .docx',
      'Вопрос  с   двойным пробелом',
    ];
    for (const h of headings) {
      expect(slugify(h)).toBe(githubSlug(h));
    }
  });
});

describe('extractHeadings', () => {
  const content = [
    '# Заголовок статьи',
    '',
    'Вступительный абзац.',
    '',
    '## Что такое АОСР?',
    '',
    'Текст раздела.',
    '',
    '### Подраздел про сроки',
    '',
    '#### H4 не попадает в оглавление',
    '',
    '## Частые вопросы',
  ].join('\n');

  it('извлекает H2 и H3, игнорируя H1 и H4', () => {
    const headings = extractHeadings(content);
    expect(headings).toEqual([
      { level: 2, text: 'Что такое АОСР?', id: 'что-такое-аоср' },
      { level: 3, text: 'Подраздел про сроки', id: 'подраздел-про-сроки' },
      { level: 2, text: 'Частые вопросы', id: 'частые-вопросы' },
    ]);
  });

  it('возвращает [] для контента без заголовков', () => {
    expect(extractHeadings('Просто текст.\nЕщё строка.')).toEqual([]);
  });
});
