import { describe, it, expect } from 'vitest';
import { fmt } from './shared';

// toLocaleString('ru-RU') разделяет разряды неразрывным пробелом (U+00A0
// или U+202F в зависимости от версии ICU) — нормализуем к обычному пробелу,
// чтобы тест не зависел от сборки Node.
const norm = (s: string) => s.replace(/\s/g, ' ');

describe('fmt', () => {
  it('разделяет разряды пробелом и использует запятую как десятичный разделитель', () => {
    expect(norm(fmt(1_234_567.891))).toBe('1 234 567,89');
  });

  it('не добавляет дробную часть целым числам', () => {
    expect(norm(fmt(48_000))).toBe('48 000');
    expect(fmt(0)).toBe('0');
  });

  it('ограничивает дробную часть двумя знаками с округлением', () => {
    expect(fmt(0.126)).toBe('0,13');
  });

  it('не дописывает нули к короткой дробной части', () => {
    expect(fmt(0.5)).toBe('0,5');
  });

  it('форматирует отрицательные суммы', () => {
    expect(norm(fmt(-1500.5))).toBe('-1 500,5');
  });
});
